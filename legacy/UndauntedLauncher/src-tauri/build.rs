//! Tauri's build step, plus two things made from the launcher's own sources:
//!
//! - the app's commands under the ACL (row L8): each command in `src/bridge/spec.rs` gets
//!   `allow-<command>` / `deny-<command>` permissions, and the page may call only what
//!   `capabilities/main.json` grants;
//! - the languages and the backend's text (row L14): `gen/strings.json` (the page's `STRINGS`, exported
//!   by `test/strings-export.test.ts`) becomes the `Language` enum and one lookup table per language,
//!   so a language added to the page appears here by rebuilding.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

/// The command names in the order of `COMMANDS` in spec.rs (read as text: build.rs cannot use the crate).
fn command_names() -> Vec<&'static str> {
    let spec = fs::read_to_string("src/bridge/spec.rs").unwrap_or_default();
    let list = spec.split_once("pub const COMMANDS").map_or("", |(_, rest)| rest);
    let list = list.split_once("];").map_or("", |(list, _)| list);
    // rustfmt may put the name on the next line: `command(` then `"name",`
    list.split("command(")
        .skip(1)
        .filter_map(|item| item.trim_start().strip_prefix('"')?.split_once('"'))
        .map(|(name, _)| &*Box::leak(name.to_owned().into_boxed_str()))
        .collect()
}

/// `en` -> `En`
fn variant(code: &str) -> String {
    let mut chars = code.chars();
    chars
        .next()
        .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
        .unwrap_or_default()
}

fn languages() -> String {
    let text = fs::read_to_string("gen/strings.json").unwrap_or_else(|error| panic!("gen/strings.json: {error}"));
    let strings: serde_json::Map<String, serde_json::Value> =
        serde_json::from_str(&text).unwrap_or_else(|error| panic!("gen/strings.json: {error}"));
    let codes: Vec<&String> = strings.keys().collect();
    assert!(!codes.is_empty(), "gen/strings.json has no languages");
    for code in &codes {
        assert!(
            code.len() == 2 && code.bytes().all(|byte| byte.is_ascii_lowercase()),
            "language code {code:?}"
        );
    }

    let mut out = String::from("// Generated by build.rs from gen/strings.json.\n\n");
    out.push_str("/// The launcher's languages, in the order of the page's registry (`src/shared/i18n/index.ts`).\n");
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]\n");
    out.push_str("#[cfg_attr(test, derive(ts_rs::TS))]\npub enum Language {\n");
    for code in &codes {
        let _ = writeln!(out, "    #[serde(rename = {code:?})]\n    {},", variant(code));
    }
    out.push_str("}\n\nimpl Language {\n");
    let _ = writeln!(
        out,
        "    pub const ALL: [Self; {}] = [{}];",
        codes.len(),
        codes
            .iter()
            .map(|code| format!("Self::{}", variant(code)))
            .collect::<Vec<_>>()
            .join(", ")
    );
    out.push_str("\n    pub fn code(self) -> &'static str {\n        match self {\n");
    for code in &codes {
        let _ = writeln!(out, "            Self::{} => {code:?},", variant(code));
    }
    out.push_str("        }\n    }\n\n    /// This language's text, sorted by key.\n    fn table(self) -> &'static [(&'static str, &'static str)] {\n        match self {\n");
    for code in &codes {
        let _ = writeln!(
            out,
            "            Self::{} => {},",
            variant(code),
            code.to_ascii_uppercase()
        );
    }
    out.push_str("        }\n    }\n}\n");
    for (code, table) in &strings {
        let table = table
            .as_object()
            .unwrap_or_else(|| panic!("gen/strings.json: {code} is not an object"));
        let mut entries: Vec<(&String, &str)> = table
            .iter()
            .map(|(key, value)| {
                (
                    key,
                    value.as_str().unwrap_or_else(|| panic!("{code}.{key} is not text")),
                )
            })
            .collect();
        entries.sort_unstable_by(|a, b| a.0.cmp(b.0));
        let _ = writeln!(out, "\nstatic {}: &[(&str, &str)] = &[", code.to_ascii_uppercase());
        for (key, value) in entries {
            let _ = writeln!(out, "    ({key:?}, {value:?}),");
        }
        out.push_str("];\n");
    }
    out
}

fn main() {
    println!("cargo:rerun-if-changed=src/bridge/spec.rs");
    println!("cargo:rerun-if-changed=permissions");
    println!("cargo:rerun-if-changed=../isolation");
    println!("cargo:rerun-if-changed=gen/strings.json");

    let out_dir = std::env::var("OUT_DIR").unwrap_or_else(|error| panic!("OUT_DIR: {error}"));
    if let Err(error) = fs::write(Path::new(&out_dir).join("languages.rs"), languages()) {
        panic!("languages.rs: {error}");
    }

    let names = command_names();
    assert!(!names.is_empty(), "no commands found in src/bridge/spec.rs");
    let commands: &'static [&'static str] = Box::leak(names.into_boxed_slice());
    let attributes = tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(commands));
    if let Err(error) = tauri_build::try_build(attributes) {
        panic!("tauri build step failed: {error:#}");
    }
}
