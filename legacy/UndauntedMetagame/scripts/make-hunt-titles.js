// Builds src/vendor/hunt_titles.json, the friendly names /undaunted/api/ServerStatus
// shows for running hunts, from the deploy server's copies of the game's hunt tables.
//   node scripts/make-hunt-titles.js
// Every name comes from the tables' own HuntName text, except the short manual list
// below. Re-run it after the deploy server's tables change.
const fs = require("fs");
const path = require("path");

const VENDOR = path.join(__dirname, "..", "..", "UndauntedDeployServer", "src", "vendor");
const OUT = path.join(__dirname, "..", "src", "vendor", "hunt_titles.json");

const PlayerHunts = JSON.parse(fs.readFileSync(path.join(VENDOR, "player_hunts_table.json"), "utf8"))[0].Rows;
const MatchmakerHunts = JSON.parse(fs.readFileSync(path.join(VENDOR, "matchmaker_hunts_table.json"), "utf8"))[0].Rows;

// Behemoths no pursuit hunt names. The tutorial's Gnasher has its own blueprint.
const MANUAL_BEHEMOTHS = {
    mcbeaver_tutorial_bp: "Gnasher"
};

// "~DNT~ Frost Escalation {MinEscalationLevel}-{MaxEscalationLevel}" -> "Frost Escalation"
function Clean(Name) {
    if (typeof Name !== "string") return "";
    return Name.replace(/^~DNT~\s*/, "").replace(/\s*\{[^}]*\}(\s*-\s*\{[^}]*\})?/g, "").trim();
}

// "/Game/Monsters/lerawr/lerawr_beta_bp.lerawr_beta_bp_C" -> "lerawr_beta_bp"
function Blueprint(AssetPath) {
    if (typeof AssetPath !== "string" || AssetPath === "None" || AssetPath.length === 0) return undefined;
    return AssetPath.split("/").pop().split(".")[0].toLowerCase();
}

const playerHunts = {};
const matchmakerHunts = {};
const behemoths = {};

for (const [HuntId, Row] of Object.entries(PlayerHunts)) {
    const Name = Clean(Row.HuntName?.LocalizedString);
    if (Name.length === 0) continue;
    playerHunts[HuntId] = Name;

    // A pursuit is named after its behemoth ("Lesser Embermane", "Heroic Koshai")
    if (!/_Pursuit_/.test(HuntId)) continue;
    const Ids = (Row.MatchmakerHuntIDs || []).map((Entry) => Entry.RowName).filter((Id) => MatchmakerHunts[Id] != undefined);
    if (Ids.length !== 1) continue;

    matchmakerHunts[Ids[0]] = Name;

    const Bp = Blueprint(MatchmakerHunts[Ids[0]].SpecificBehemoth?.BehemothAsset?.AssetPathName);
    if (Bp == undefined) continue;
    // Heroic hunts reuse the alpha blueprint: the blueprint keeps the plain name
    const Current = behemoths[Bp];
    if (Current == undefined || (Current.startsWith("Heroic ") && !Name.startsWith("Heroic "))) {
        behemoths[Bp] = Name;
    }
}

Object.assign(behemoths, MANUAL_BEHEMOTHS);

const Sorted = (Object_) => Object.fromEntries(Object.keys(Object_).sort().map((Key) => [Key, Object_[Key]]));

fs.writeFileSync(OUT, JSON.stringify({
    _source: "Generated by scripts/make-hunt-titles.js from UndauntedDeployServer/src/vendor (the game's hunt tables). Do not edit by hand.",
    playerHunts: Sorted(playerHunts),
    matchmakerHunts: Sorted(matchmakerHunts),
    behemoths: Sorted(behemoths)
}, null, 2) + "\n");

console.log(`hunt titles: ${Object.keys(playerHunts).length} player hunts, ${Object.keys(matchmakerHunts).length} matchmaker hunts, ${Object.keys(behemoths).length} behemoths -> ${OUT}`);
