test('temporary account-only bans expire, preserve history and reject invalid durations',()=>{
  const db=GetDb();db.insert(users).values({userId:'UID-temp-ban',name:'Temporary',notes:0}).run();
  const now=Date.now();SetAccountBan('UID-temp-ban','Verified evidence',true,null,'owner',168);
  const ban=ModerationInfo('UID-temp-ban').ban as any;
  assert.ok(ban.expires_at>=now+7*86400000 && ban.expires_at<=Date.now()+7*86400000);
  assert.equal(BanFor('UID-temp-ban')?.reason,'Verified evidence');
  assert.equal(BanFor('UID-unrelated','203.0.113.9'),undefined);
  assert.ok(ModerationLog('bans').rows.some((r:any)=>r.account_id==='UID-temp-ban'));
  for(const hours of [0,-1,721,1.5,NaN,'168'])assert.throws(()=>SetAccountBan('UID-temp-ban','reason',true,null,'owner',hours),/invalid_duration/);
  assert.throws(()=>SetAccountBan('UID-temp-ban','reason',true,'203.0.113.9','owner',168),/address_not_observed/);
  db.$client.prepare('UPDATE account_bans SET expires_at=? WHERE account_id=?').run(Date.now()-1,'UID-temp-ban');
  assert.equal(BanFor('UID-temp-ban'),undefined);
  assert.equal((ModerationInfo('UID-temp-ban').ban as any).active,0);
  assert.ok(!ModerationLog('bans').rows.some((r:any)=>r.account_id==='UID-temp-ban'));
  assert.ok(ModerationLog('events').rows.some((r:any)=>r.account_id==='UID-temp-ban'&&r.expires_at===ban.expires_at));
  assert.throws(()=>ModerationLog('events',-1),/invalid_offset/);
  SetAccountBan('UID-temp-ban','Verified again',true,null,'owner',168);
  SetAccountBan('UID-temp-ban','Appeal accepted',false,null,'owner');
  assert.equal(BanFor('UID-temp-ban'),undefined);
});
test('temporary observed-IP bans expire and revoke with the account sanction',()=>{
  const db=GetDb(),account='UID-temp-ip-ban',address='203.0.113.123';
  db.insert(users).values({userId:account,name:'TemporaryIP',notes:0}).run();
  const request:any={socket:{remoteAddress:address},headers:{}};
  assert.throws(()=>SetAccountBan(account,'Verified evidence',true,address,'owner',168),/address_not_observed/);
  assert.equal(ModerationInfo(account).ban,null);
  RecordPlayingAddress(request,account,Date.now()-90001);
  assert.throws(()=>SetAccountBan(account,'Verified evidence',true,address,'owner',168),/address_not_observed/);
  RecordPlayingAddress(request,account);
  const now=Date.now();
  SetAccountBan(account,'Verified evidence',true,address,'owner',168);
  const ban=ModerationInfo(account).ban as any;
  assert.ok(ban.expires_at>=now+7*86400000 && ban.expires_at<=Date.now()+7*86400000);
  assert.equal(BanFor(account)?.reason,'Verified evidence');
  assert.equal(BanFor('UID-unrelated',address)?.reason,'Verified evidence');
  assert.equal(BanFor('UID-unrelated','203.0.113.124'),undefined);
  db.$client.prepare('UPDATE account_bans SET expires_at=? WHERE account_id=?').run(Date.now()-1,account);
  assert.equal(BanFor(account),undefined);
  assert.equal(BanFor('UID-unrelated',address),undefined);
  SetAccountBan(account,'Verified again',true,address,'owner',168);
  EndPlayingAddress(account);
  SetAccountBan(account,'Appeal accepted',false,null,'owner');
  assert.equal(BanFor(account),undefined);
  assert.equal(BanFor('UID-unrelated',address),undefined);
});
test('trusted IP logging, account/IP bans, required reasons, JWT revocation and unban',async()=>{
  const db=GetDb();
  db.insert(users).values([{userId:'UID-ban-test',name:'BanTest',notes:0},{userId:'UID-admin-test',name:'AdminTest',notes:0,isAdmin:true}]).run();
  const key='UUK_'+ 'a'.repeat(48),admin='UUK_'+'b'.repeat(48);
  db.insert(userapikeys).values([{userId:'UID-ban-test',keyHash:HashUserAPIKey(key)},{userId:'UID-admin-test',keyHash:HashUserAPIKey(admin)}]).run();
  const token=SignMetagameJWTForUid('UID-ban-test');
  process.env.GATEWAY_SECRET='test-gateway-secret';
  const req:any={socket:{remoteAddress:'127.0.0.1'},headers:{'x-forwarded-for':'203.0.113.9'}};
  const response:any={status(){return this},json(){return this}};
  CheckPlayerAccess(req,response,'UID-ban-test');
  assert.equal(ModerationInfo('UID-ban-test').addresses.length,0);
  RecordPlayingAddress(req,'UID-ban-test');
  assert.equal(ModerationInfo('UID-ban-test').addresses.length,0);
  req.headers['x-dauntless-gateway']='test-gateway-secret';
  CheckPlayerAccess(req,response,'UID-ban-test');
  assert.equal(ModerationInfo('UID-ban-test').addresses.length,0);
  RecordPlayingAddress(req,'UID-ban-test');
  assert.equal(ModerationInfo('UID-ban-test').username,'BanTest');
  assert.equal(ModerationInfo('UID-ban-test').addresses.length,1);
  EndPlayingAddress('UID-ban-test');
  assert.equal(ModerationInfo('UID-ban-test').addresses.length,0);
  RecordPlayingAddress(req,'UID-ban-test',Date.now()-90001);
  ExpirePlayingAddresses();
  assert.equal(ModerationInfo('UID-ban-test').addresses.length,0);
  RecordPlayingAddress(req,'UID-ban-test');
  assert.equal((db.$client.prepare('SELECT count(*) n FROM player_addresses').get() as any).n,0);
  assert.throws(()=>SetAccountBan('UID-ban-test',' ',true,null,'owner'),/invalid_ban/);
  assert.throws(()=>SetAccountBan('UID-admin-test','reason',true,null,'owner'),/protected/);
  assert.throws(()=>SetAccountBan('UID-ban-test','reason',true,'203.0.113.10','owner'),/not_observed/);
  SetAccountBan('UID-ban-test','Repeated harassment',true,'203.0.113.9','owner');
  assert.equal(BanFor('UID-other','203.0.113.9')?.reason,'Repeated harassment');
  assert.throws(()=>ValidateMetagameJWTAndGetPayload(token),/account_banned/);
  const server=app.listen(0,'127.0.0.1');await new Promise<void>(r=>server.once('listening',r));
  const port=(server.address() as any).port;
  try {
    const request=async(path:string,k:string,body?:unknown)=>fetch(`http://127.0.0.1:${port}${path}`,{method:body?'POST':'GET',headers:{'x-undaunted-user-api-key':k,'content-type':'application/json'},body:body?JSON.stringify(body):undefined});
    assert.equal((await request('/undaunted/api/ModerationLog?kind=events',key)).status,403);
    assert.equal((await request('/undaunted/api/ModerationLog?kind=events',admin)).status,200);
    assert.equal((await request('/undaunted/api/ModerationLog?kind=bans&offset=-1',admin)).status,400);
    const reply=await request('/undaunted/api/GetUserInfo',key);assert.equal(reply.status,403);assert.deepEqual(await reply.json(),{error:'account_banned',reason:'Repeated harassment'});
    assert.equal((await request('/undaunted/api/Moderation/UID-ban-test',key)).status,403);
    assert.equal((await request('/undaunted/api/Moderation',admin,{accountId:'UID-ban-test',reason:'Appeal accepted',active:false})).status,200);
    assert.equal((await request('/undaunted/api/GetUserInfo',key)).status,200);
    assert.equal(BanFor('UID-other','203.0.113.9'),undefined);
    assert.ok(ValidateMetagameJWTAndGetPayload(token));
    const heartbeat=await fetch(`http://127.0.0.1:${port}/heartbeat`,{method:'POST',headers:{authorization:'Bearer '+token,'content-type':'application/json','x-dauntless-gateway':'test-gateway-secret','x-forwarded-for':'203.0.113.9'},body:JSON.stringify({map:'ramsgate',state:'city'})});
    assert.equal(heartbeat.status,200);
    assert.equal(ModerationInfo('UID-ban-test').addresses.length,1);
    assert.equal((await request('/undaunted/api/PlayingEnded',key,{})).status,204);
    assert.equal(ModerationInfo('UID-ban-test').addresses.length,0);
    assert.equal((await request('/undaunted/api/GetUserInfo',key)).status,200);
    assert.equal(ModerationInfo('UID-ban-test').addresses.length,0);
  }finally{await new Promise<void>((r,j)=>server.close(e=>e?j(e):r()));delete process.env.GATEWAY_SECRET;}
});
