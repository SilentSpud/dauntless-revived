import "./setup";
import "./authenv";
import "./appenv";
import { Mounts } from "./routemounts";
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { app } from "../src/app";

// Route inventory (MIGRATION_PLAN.md M3): every route the Express app serves, in match order, with
// its method, path and middleware chain, written to routes.json. The Rust metagame's router test
// checks every entry against its own table, so this test fails when the two would drift: after
// changing a route, run `WRITE_ROUTES=1 npm test` and commit routes.json. The chain is what runs
// before the handler: middleware mounted on the route's router with router.use, then the route's
// own. A router.use entry is also listed in place with the method USE. Anonymous functions are named
// after the middleware module export they are (the rate limiters); "app" is the app-wide chain.

const ROUTES_FILE = path.join(__dirname, "../../routes.json");
const MIDDLEWARE_DIR = path.join(__dirname, "../src/middleware");

type Entry = { method: string; path: string; middleware: string[] };

function ExportNames(){
    const Names = new Map<unknown, string>();

    for(const File of fs.readdirSync(MIDDLEWARE_DIR).filter((Name) => Name.endsWith(".js")).sort()){
        for(const [Name, Value] of Object.entries(require(path.join(MIDDLEWARE_DIR, File)))){
            if(typeof Value === "function" && !Names.has(Value)){
                Names.set(Value, Name);
            }
        }
    }

    return Names;
}

function NameOf(Fn: any, Names: Map<unknown, string>){
    return Names.get(Fn) ?? (Fn.name && Fn.name !== "<anonymous>" ? Fn.name : "<anonymous>");
}

function MountOf(Fn: unknown){
    const Paths = Mounts.get(Fn) ?? [];
    assert.equal(Paths.length, 1, "every router and router-level middleware is mounted exactly once");
    return Paths[0];
}

function Join(Prefix: string, Route: string){
    return (Prefix === "/" ? "" : Prefix) + Route;
}

function Inventory(){
    const Names = ExportNames();
    const AppMiddleware: string[] = [];
    const Routes: Entry[] = [];

    for(const Layer of (app as any).router.stack){
        if(!Layer.handle?.stack){
            AppMiddleware.push(NameOf(Layer.handle, Names));
            continue;
        }

        const Prefix = MountOf(Layer.handle);
        const RouterMiddleware: { path: string; name: string }[] = [];

        for(const RouteLayer of Layer.handle.stack){
            if(!RouteLayer.route){
                const Use = { path: MountOf(RouteLayer.handle), name: NameOf(RouteLayer.handle, Names) };
                RouterMiddleware.push(Use);
                // Listed in place too, since it also runs for requests no later route answers.
                Routes.push({ method: "USE", path: Join(Prefix, Use.path), middleware: [Use.name] });
                continue;
            }

            const RoutePath: string = RouteLayer.route.path;
            const Before = RouterMiddleware
                .filter((Use) => Use.path === "/" || RoutePath.toLowerCase() === Use.path.toLowerCase() || RoutePath.toLowerCase().startsWith(`${Use.path.toLowerCase()}/`))
                .map((Use) => `use(${Use.path}) ${Use.name}`);

            for(const Method of Object.keys(RouteLayer.route.methods)){
                const Own = RouteLayer.route.stack.filter((Handler: any) => Handler.method === undefined || Handler.method === Method);
                Routes.push({
                    method: Method.toUpperCase(),
                    path: Join(Prefix, RoutePath),
                    middleware: [...Before, ...Own.slice(0, -1).map((Handler: any) => NameOf(Handler.handle, Names))]
                });
            }
        }
    }

    return {
        about: "Generated by UndauntedMetagame/test/routes.test.ts (WRITE_ROUTES=1 npm test). Every route of the Node metagame in match order; see MIGRATION_PLAN.md M3.",
        app: AppMiddleware,
        routes: Routes
    };
}

describe("route inventory", () => {
    it("routes.json lists every route with its middleware", () => {
        const Text = `${JSON.stringify(Inventory(), null, 2)}\n`;

        if(process.env.WRITE_ROUTES === "1"){
            fs.writeFileSync(ROUTES_FILE, Text);
        }

        assert.equal(fs.readFileSync(ROUTES_FILE, "utf8").replace(/\r\n/g, "\n"), Text, "routes.json is out of date: run WRITE_ROUTES=1 npm test and commit it");
    });
});
